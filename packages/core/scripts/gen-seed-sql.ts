/**
 * Generates supabase/seed.sql from the TypeScript seed data (single source of truth).
 * Run: npm run seed:sql
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { INGREDIENTS } from '../src/seed/ingredients.ts';
import { RECIPES } from '../src/seed/recipes.ts';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [
  '-- GENERATED by packages/core/scripts/gen-seed-sql.ts – do not edit by hand.',
  'begin;',
  'delete from public.recipe_ingredients where recipe_id in (select id from public.recipes where source = \'curated\');',
  'delete from public.recipes where source = \'curated\';',
  'delete from public.package_sizes;',
  'delete from public.ingredient_aliases;',
  '',
];

for (const i of INGREDIENTS) {
  out.push(
    `insert into public.ingredients (id, name_de, base_unit, grams_per_piece, density_g_per_ml, unit_weights, aisle, shelf_life_days, allergens, diet_class, is_staple) values (` +
      [q(i.id), q(i.name), q(i.baseUnit), q(i.gramsPerPiece), q(i.densityGPerMl), json(i.unitWeights ?? {}), q(i.aisle), q(i.shelfLifeDays), arr(i.allergens), q(i.dietClass), q(!!i.isStaple)].join(', ') +
      `) on conflict (id) do update set name_de = excluded.name_de, base_unit = excluded.base_unit, grams_per_piece = excluded.grams_per_piece, density_g_per_ml = excluded.density_g_per_ml, unit_weights = excluded.unit_weights, aisle = excluded.aisle, shelf_life_days = excluded.shelf_life_days, allergens = excluded.allergens, diet_class = excluded.diet_class, is_staple = excluded.is_staple;`,
  );
  for (const a of i.aliases) out.push(`insert into public.ingredient_aliases (ingredient_id, alias) values (${q(i.id)}, ${q(a)});`);
  for (const p of i.packages)
    out.push(`insert into public.package_sizes (id, ingredient_id, amount, unit, label) values (${q(p.id)}, ${q(i.id)}, ${p.amount}, ${q(i.baseUnit)}, ${q(p.label)});`);
}
out.push('');

for (const r of RECIPES) {
  out.push(
    `insert into public.recipes (id, title, description, servings, prep_minutes, category, tags, instructions, source, is_public) values (` +
      [q(r.id), q(r.title), q(r.description), r.servings, r.prepMinutes, q(r.category), arr(r.tags), json(r.steps), q('curated'), 'true'].join(', ') +
      ');',
  );
  r.ingredients.forEach((ri, idx) =>
    out.push(
      `insert into public.recipe_ingredients (recipe_id, ingredient_id, position, amount_base, display_amount, display_unit, optional) values (` +
        [q(r.id), q(ri.ingredientId), idx, ri.amountBase, ri.displayAmount, q(ri.displayUnit), q(!!ri.optional)].join(', ') +
        ');',
    ),
  );
}
out.push('commit;', '');

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../../../supabase/seed.sql');
writeFileSync(target, out.join('\n'), 'utf8');
console.log(`seed.sql: ${INGREDIENTS.length} Zutaten, ${RECIPES.length} Rezepte → ${target}`);
