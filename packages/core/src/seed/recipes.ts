import { toBase } from '../units.ts';
import type { MealCategory, Recipe } from '../types.ts';
import { INGREDIENTS } from './ingredients.ts';

const byId = new Map(INGREDIENTS.map((i) => [i.id, i]));

type Line = [ingredientId: string, amount: number, unit: string, optional?: boolean];

function R(
  id: string,
  title: string,
  category: MealCategory,
  prepMinutes: number,
  servings: number,
  tags: string[],
  description: string,
  lines: Line[],
  steps: string[],
): Recipe {
  return {
    id,
    title,
    description,
    category,
    prepMinutes,
    servings,
    tags,
    source: 'curated',
    steps,
    ingredients: lines.map(([ingredientId, amount, unit, optional]) => {
      const ing = byId.get(ingredientId);
      if (!ing) throw new Error(`Rezept ${id}: unbekannte Zutat ${ingredientId}`);
      return {
        ingredientId,
        amountBase: Math.round(toBase(ing, amount, unit) * 100) / 100,
        displayAmount: amount,
        displayUnit: unit,
        ...(optional ? { optional: true } : {}),
      };
    }),
  };
}

